enter= input("Enter a number between 1 and 7: ")
if enter == "1":
    print("Monday")
elif enter == "2":
    print("Tuesday")
elif enter == "3":
    print("Wednesday")
elif enter == "4":
    print("Thursday")
elif enter == "5":
    print("Friday")
elif enter == "6":
    print("Saturday")
elif enter == "7":
    print("Sunday")
else:
    print("Invalid input. Please enter a number between 1 and 7.")